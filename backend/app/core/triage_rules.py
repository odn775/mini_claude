"""急危重症（红旗症状）识别。

这是确定性的安全兜底：只要用户文本命中，入口层就必须无条件给出急诊提示，
不等待模型判断，也不依赖模型是否「想起来」提醒。识别结果不参与诊断。
"""

from __future__ import annotations

# 分组：标签 → 触发关键词
RED_FLAGS: dict[str, list[str]] = {
    "胸痛或压榨性胸闷": ["胸痛", "胸口疼", "胸口痛", "压榨", "胸口压迫", "心前区痛"],
    "呼吸困难": ["呼吸困难", "喘不上气", "透不过气", "不能呼吸", "窒息"],
    "意识障碍或抽搐": ["意识不清", "昏迷", "叫不醒", "抽搐", "晕倒", "晕厥", "意识丧失"],
    "大出血": ["大出血", "大量出血", "呕血", "咯血", "便血不止", "血流不止"],
    "剧烈头痛": ["剧烈头痛", "爆炸样头痛", "头痛欲裂"],
    "疑似中毒": ["中毒", "误服", "农药", "过量服药"],
    "严重过敏": ["过敏性休克", "喉头水肿", "全身荨麻疹伴憋气"],
    "自伤风险": ["自杀", "想死", "轻生", "不想活"],
    "孕产急症": ["孕晚期出血", "胎动消失", "临产大出血"],
    "儿童危重": ["高热惊厥", "婴儿抽搐", "孩子叫不醒"],
}

ADVICE = (
    "检测到可能属于急危重症的表现，请立即拨打 120 或前往最近医院急诊科，"
    "不要等待线上建议。"
)


def detect(text: str) -> list[str]:
    """返回命中的红旗症状标签（去重、保持定义顺序）。"""
    if not text:
        return []
    return [label for label, words in RED_FLAGS.items() if any(w in text for w in words)]


def alert_text(matched: list[str]) -> str:
    """入口层展示的提示文案。"""
    if not matched:
        return ""
    return f"[急诊提示] 命中：{'、'.join(matched)}。{ADVICE}"
